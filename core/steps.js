// GUI steps -> steps.lua. The steps editor doesn't drive the engine directly: it generates the
// same API calls a teacher would type, and the engine runs them like any other script.
//
// A step is one of
//   { op: 'color', target, color, dur, together }
//   { op: 'move',  target, x, y, dur, together }
//   { op: 'wait',  dur }
// target is an editor object id; dur is in ms. Steps play one after another, except that a
// step with together=true starts at the same time as the step before it.

import { variableNames, luaString } from './stage_file.js';

const sec = (ms) => String(Number((ms / 1000).toFixed(3)));

/** Drops steps whose node or edge no longer exists on the stage. */
export function pruneSteps(steps, scene) {
  return steps.filter((s) => s.op === 'wait' || scene.get(s.target));
}

export function stepsToLua(steps, scene) {
  if (!steps.length) return '';
  const names = variableNames(scene);
  const ref = (id) => {
    const o = scene.get(id);
    return o.kind === 'node' ? names.get(id) : `edge_of(${names.get(o.a)}, ${names.get(o.b)})`;
  };

  const lines = ['-- steps.lua (generated by the GEPV1 steps editor)'];
  let group = [], longest = 0; // calls that start together, and how long the longest one lasts
  const flush = () => {
    if (!group.length) return;
    lines.push(...group.slice(0, -1), `${group.at(-1)}; wait(${sec(longest)})`);
    group = [];
    longest = 0;
  };

  for (const s of steps) {
    if (s.op === 'wait') { flush(); lines.push(`wait(${sec(s.dur)})`); continue; }
    if (!s.together) flush();
    group.push(s.op === 'color'
      ? `color(${ref(s.target)}, ${luaString(s.color)}, ${sec(s.dur)})`
      : `move(${ref(s.target)}, ${Math.round(s.x)}, ${Math.round(s.y)}, ${sec(s.dur)})`);
    longest = Math.max(longest, s.dur);
  }
  flush();
  return lines.join('\n') + '\n';
}

/**
 * Running stage.lua numbers objects 1..n in the order it creates them (nodes, then edges), while
 * editor ids can have gaps after deletions. Returns a state from sceneAt() with editor ids, so
 * the editor can show "the stage after the steps" and still know which object was clicked.
 */
export function toEditorIds(state, result, scene) {
  const order = [...scene.nodes(), ...scene.edges()].map((o) => o.id);
  const map = new Map(result.timeline.commands.slice(0, result.stageCommands).map((c, i) => [c.id, order[i]]));
  const id = (x) => map.get(x) ?? x;
  return {
    nodes: state.nodes.map((n) => ({ ...n, id: id(n.id) })),
    edges: state.edges.map((e) => ({ ...e, id: id(e.id), a: id(e.a), b: id(e.b) })),
  };
}
