// stage.lua serializer: the GUI editor saves the stage as plain GEPV1 API calls,
// i.e. the same code a teacher could write by hand. Loading a stage = running it.

import { API_NAMES } from './lua_api.js';
import { sizeOf, defaultColor } from './shapes.js';
import { DEFAULT_EDGE_COLOR } from './scene.js';

const LUA_KEYWORDS = new Set(('and break do else elseif end false for function goto if in local nil not or ' +
  'repeat return then true until while').split(' '));
// Globals a variable must not shadow (the API itself and the Lua standard library).
const RESERVED = new Set([...API_NAMES, 'print', 'math', 'string', 'table', 'pairs', 'ipairs', 'type',
  'tostring', 'tonumber', 'select', 'error', 'assert', 'pcall', 'xpcall', 'next', 'rawget', 'rawset',
  'rawequal', 'rawlen', 'setmetatable', 'getmetatable', 'load', 'unpack', 'require', '_G', '_ENV', '_VERSION']);

/** Lua string literal for any JS string. */
export function luaString(s) {
  return '"' + String(s).replace(/[\\"\x00-\x1f\x7f]/g, (ch) => {
    if (ch === '\\') return '\\\\';
    if (ch === '"') return '\\"';
    if (ch === '\n') return '\\n';
    if (ch === '\t') return '\\t';
    return '\\' + ch.charCodeAt(0).toString().padStart(3, '0');
  }) + '"';
}

export function isUsableName(s) {
  return /^[A-Za-z_][A-Za-z0-9_]*$/.test(s) && !LUA_KEYWORDS.has(s) && !RESERVED.has(s);
}

/** Variable name for each node: its label when that is a safe, unique Lua identifier. */
export function variableNames(scene) {
  const names = new Map(), used = new Set();
  const nodes = scene.nodes();
  for (const nd of nodes) {
    if (isUsableName(nd.label) && !used.has(nd.label)) { names.set(nd.id, nd.label); used.add(nd.label); }
  }
  let k = 1;
  for (const nd of nodes) {
    if (names.has(nd.id)) continue;
    while (used.has(`node_${k}`)) k++;
    names.set(nd.id, `node_${k}`);
    used.add(`node_${k}`);
  }
  return names;
}

/** The API call that makes each shape. */
export const SHAPE_CALL = { circle: 'node', rect: 'rect', triangle: 'triangle', text: 'text' };

/** The optional size arguments of node(), rect(), …: '' (normal), ', 1.5' (both ways) or ', 2, 1'. */
export function sizeArgs(size) {
  const z = sizeOf(size), f = (v) => Number(v.toFixed(3));
  if (z.w === z.h) return z.w === 1 ? '' : `, ${f(z.w)}`;
  return `, ${f(z.w)}, ${f(z.h)}`;
}

export function toStageLua(scene) {
  const names = variableNames(scene);
  const lines = ['-- stage.lua (generated by the GEPV1 editor)'];
  const colours = [];
  for (const nd of scene.nodes()) {
    lines.push(`${names.get(nd.id)} = ${SHAPE_CALL[nd.shape ?? 'circle']}(${luaString(nd.label)}, ${Math.round(nd.x)}, ${Math.round(nd.y)}${sizeArgs(nd.size)})`);
    if (nd.color && nd.color !== defaultColor(nd.shape ?? 'circle')) colours.push(`color(${names.get(nd.id)}, ${luaString(nd.color)}, 0)`);
  }
  for (const e of scene.edges()) {
    lines.push(`${e.directed ? 'arrow' : 'edge'}(${names.get(e.a)}, ${names.get(e.b)})`);
    if (e.color && e.color !== DEFAULT_EDGE_COLOR) colours.push(`color(edge_of(${names.get(e.a)}, ${names.get(e.b)}), ${luaString(e.color)}, 0)`);
  }
  return [...lines, ...colours].join('\n') + '\n';
}
