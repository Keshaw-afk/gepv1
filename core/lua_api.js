// Lua API: runs stage.lua + steps.lua + script.lua in an embedded Lua VM (Fengari) and turns every
// API call into a command on the timeline, tagged with the file and line that made it
// (cmd.src = { file: 'script.lua', line: 6 }) and the object's name at that moment (cmd.name), so
// traces stay readable after an object is removed. Nothing is drawn here (record, then play).
//
// `fengari` is passed in so the same module works in Node (npm package) and in the
// browser (window.fengari from fengari-web).

import { Scene, DEFAULT_EDGE_COLOR } from './scene.js';
import { Timeline, toMs } from './timeline.js';
import { parseColor } from './colors.js';
import { defaultColor, SIZE } from './shapes.js';
import { smoothPath, pointAlong } from './paths.js';
import { EASES, ease } from './easing.js';

export const DEFAULT_DUR_MS = 500;
const MAX_INSTRUCTIONS = 50_000_000; // guards against infinite loops freezing the page
const HOOK_EVERY = 100_000;
const MAX_COMMANDS = 50_000;

// Every global the API defines (generated variable names must never shadow these).
export const API_NAMES = ['node', 'rect', 'triangle', 'text', 'edge', 'arrow', 'color', 'move', 'remove',
  'size', 'path', 'wait', 'pos', 'neighbors', 'edge_of'];

export class ScriptError extends Error {}

/**
 * Runs stage.lua, then steps.lua (generated by the GUI steps editor), then script.lua,
 * all in one Lua state (one clock, shared globals). Returns
 *   { scene, timeline, log, stageCommands }
 * scene        final logical state (what neighbors/edge_of see)
 * timeline     every command, timestamped
 * log          lines printed with print()
 * stageCommands  how many commands came from stage.lua
 * Throws ScriptError with "file.lua:line: message" on any Lua error.
 */
export function runProgram(fengari, { stage = '', steps = '', script = '' }) {
  const { lua, lauxlib, lualib, to_luastring, to_jsstring } = fengari;
  const scene = new Scene();
  const timeline = new Timeline();
  const log = [];

  const L = lauxlib.luaL_newstate();
  // Only safe, pure libraries: no io/os/package, so scripts can't touch files.
  for (const [name, open] of [['_G', lualib.luaopen_base], ['table', lualib.luaopen_table],
    ['string', lualib.luaopen_string], ['math', lualib.luaopen_math]]) {
    lauxlib.luaL_requiref(L, to_luastring(name), open, 1);
    lua.lua_pop(L, 1);
  }
  for (const g of ['dofile', 'loadfile']) { lua.lua_pushnil(L); lua.lua_setglobal(L, to_luastring(g)); }

  const fail = (msg) => lauxlib.luaL_error(L, to_luastring(msg));
  const optSeconds = (i) => {
    if (lua.lua_isnoneornil(L, i)) return DEFAULT_DUR_MS;
    const s = lauxlib.luaL_checknumber(L, i);
    if (s < 0) fail('duration must be >= 0');
    return toMs(s);
  };
  const checkObj = (i, kind) => {
    const id = lauxlib.luaL_checkinteger(L, i);
    const o = scene.get(id);
    if (!o || (kind && o.kind !== kind)) fail(`argument #${i}: no ${kind ?? 'object'} with id ${id}`);
    return id;
  };
  // Where the current API call came from, e.g. { file: 'steps.lua', line: 3 } (level 1 = the caller).
  const ar = new lua.lua_Debug();
  const caller = () => {
    if (!lua.lua_getstack(L, 1, ar)) return null;
    lua.lua_getinfo(L, to_luastring('Sl'), ar);
    return ar.currentline > 0 ? { file: to_jsstring(ar.short_src), line: ar.currentline } : null;
  };
  const emit = (cmd) => {
    if (timeline.commands.length >= MAX_COMMANDS) fail(`too many commands (limit ${MAX_COMMANDS})`);
    return timeline.add({ ...cmd, name: scene.nameOf(cmd.id), src: caller() });
  };

  // Where each node is over time (its latest move), so pos() knows where things are mid-move:
  // { from, to, t0, dur, ease }.
  const place = new Map();
  const positionAt = (id, t) => {
    const m = place.get(id);
    const f = m.dur === 0 ? 1 : Math.min(1, Math.max(0, (t - m.t0) / m.dur));
    const e = ease(m.ease, f);
    if (m.path) return f >= 1 ? { ...m.to } : pointAlong(m.path, e);
    return { x: m.from.x + (m.to.x - m.from.x) * e, y: m.from.y + (m.to.y - m.from.y) * e };
  };
  const moveTo = (id, x, y, dur, easing) => {
    const from = positionAt(id, timeline.clockMs);
    place.set(id, { from, to: { x, y }, t0: timeline.clockMs, dur, ease: easing });
    Object.assign(scene.get(id), { x, y });
    emit({ op: 'set', id, prop: 'pos', value: { x, y }, dur, ...(easing !== 'linear' && { ease: easing }) });
  };
  const optEase = (i, fallback) => {
    if (lua.lua_isnoneornil(L, i)) return fallback;
    const e = to_jsstring(lauxlib.luaL_checkstring(L, i));
    if (!(e in EASES)) fail(`unknown easing '${e}' (use ${Object.keys(EASES).map((k) => `"${k}"`).join(' or ')})`);
    return e;
  };

  const checkSize = (i) => {
    const s = lauxlib.luaL_checknumber(L, i);
    if (!(s >= SIZE.min && s <= SIZE.max)) fail(`size must be from ${SIZE.min} to ${SIZE.max} (1 is the normal size)`);
    return s;
  };
  // The create command of every object, so an instant colour in stage.lua (a coloured object on the
  // stage: color(A, "red", 0)) becomes its starting colour, not a change in the timeline.
  const created = new Map(), coloured = new Set();
  let inStage = false;
  const makeNode = (shape) => (L) => {
    const label = to_jsstring(lauxlib.luaL_checkstring(L, 1));
    const x = lauxlib.luaL_checknumber(L, 2), y = lauxlib.luaL_checknumber(L, 3);
    const w = lua.lua_isnoneornil(L, 4) ? 1 : checkSize(4);
    const size = { w, h: lua.lua_isnoneornil(L, 5) ? w : checkSize(5) };
    const id = scene.addNode(label, x, y, shape, size);
    place.set(id, { from: { x, y }, to: { x, y }, t0: timeline.clockMs, dur: 0, ease: 'linear' });
    created.set(id, emit({ op: 'create', id, kind: 'node', props: { label, shape, pos: { x, y }, color: defaultColor(shape), size } }));
    lua.lua_pushinteger(L, id);
    return 1;
  };
  const makeEdge = (directed) => (L) => {
    const a = checkObj(1, 'node'), b = checkObj(2, 'node');
    let id;
    try { id = scene.addEdge(a, b, directed); } catch (e) { fail(e.message); }
    created.set(id, emit({ op: 'create', id, kind: 'edge', props: { a, b, directed, color: DEFAULT_EDGE_COLOR } }));
    lua.lua_pushinteger(L, id);
    return 1;
  };

  const api = {
    node: makeNode('circle'),
    rect: makeNode('rect'),
    triangle: makeNode('triangle'),
    text: makeNode('text'),
    edge: makeEdge(false),
    arrow: makeEdge(true),
    color(L) {
      const id = checkObj(1);
      const c = to_jsstring(lauxlib.luaL_checkstring(L, 2));
      if (!parseColor(c)) fail(`unknown colour '${c}' (use a name like "red" or a hex code like "#ff0000")`);
      const dur = optSeconds(3);
      scene.get(id).color = c;
      const birth = created.get(id);
      if (inStage && dur === 0 && birth?.t === timeline.clockMs && !coloured.has(id)) { birth.props.color = c; return 0; }
      coloured.add(id);
      emit({ op: 'set', id, prop: 'color', value: c, dur });
      return 0;
    },
    // path(id, {{x, y}, …}, dur?, ease?): a curved move from where the node is now through the
    // points, smoothed, at even speed. The curve is worked out once and stored in the command.
    path(L) {
      const id = checkObj(1, 'node');
      lauxlib.luaL_checktype(L, 2, lua.LUA_TTABLE);
      const n = lua.lua_rawlen(L, 2);
      if (n < 1) fail('path needs at least one point, e.g. path(A, {{100, 50}, {200, 80}})');
      if (n > 500) fail('path takes at most 500 points');
      const pts = [];
      for (let i = 1; i <= n; i++) {
        lua.lua_rawgeti(L, 2, i);
        if (!lua.lua_istable(L, -1)) fail(`path point ${i} must be {x, y}`);
        lua.lua_rawgeti(L, -1, 1); lua.lua_rawgeti(L, -2, 2);
        if (!lua.lua_isnumber(L, -2) || !lua.lua_isnumber(L, -1)) fail(`path point ${i} must be {x, y}`);
        pts.push({ x: lua.lua_tonumber(L, -2), y: lua.lua_tonumber(L, -1) });
        lua.lua_pop(L, 3);
      }
      const dur = optSeconds(3), easing = optEase(4, 'linear');
      const from = positionAt(id, timeline.clockMs);
      const curve = smoothPath([from, ...pts]);
      const to = curve.at(-1);
      place.set(id, { from, to, t0: timeline.clockMs, dur, ease: easing, path: curve });
      Object.assign(scene.get(id), to);
      emit({ op: 'set', id, prop: 'pos', value: to, dur, path: curve, via: pts, ...(easing !== 'linear' && { ease: easing }) });
      return 0;
    },
    move(L) {
      const id = checkObj(1, 'node');
      const x = lauxlib.luaL_checknumber(L, 2), y = lauxlib.luaL_checknumber(L, 3);
      moveTo(id, x, y, optSeconds(4), optEase(5, 'linear'));
      return 0;
    },
    size(L) {
      // size(id, w, h, dur?, ease?) ; size(id, s) is short for size(id, s, s)
      const id = checkObj(1, 'node');
      const w = checkSize(2);
      if (lua.lua_gettop(L) > 2 && lua.lua_type(L, 3) !== lua.LUA_TNUMBER) fail('size(id, width, height, dur?) needs a width and a height (the same number twice keeps the proportions)');
      const h = lua.lua_isnoneornil(L, 3) ? w : checkSize(3);
      const dur = optSeconds(4), easing = optEase(5, 'linear');
      const value = { w, h };
      scene.get(id).size = value;
      emit({ op: 'set', id, prop: 'size', value, dur, ...(easing !== 'linear' && { ease: easing }) });
      return 0;
    },
    remove(L) {
      const id = checkObj(1);
      if (scene.isNode(id)) {
        for (const e of scene.edges()) if (e.a === id || e.b === id) emit({ op: 'remove', id: e.id });
      }
      emit({ op: 'remove', id });
      scene.remove(id);
      place.delete(id);
      return 0;
    },
    pos(L) {
      const p = positionAt(checkObj(1, 'node'), timeline.clockMs);
      lua.lua_pushnumber(L, p.x);
      lua.lua_pushnumber(L, p.y);
      return 2;
    },
    wait(L) {
      const s = lauxlib.luaL_checknumber(L, 1);
      if (s < 0) fail('wait time must be >= 0');
      timeline.wait(toMs(s));
      return 0;
    },
    neighbors(L) {
      const id = checkObj(1, 'node');
      const list = scene.neighbors(id);
      lua.lua_createtable(L, list.length, 0);
      list.forEach((n, i) => { lua.lua_pushinteger(L, n); lua.lua_rawseti(L, -2, i + 1); });
      return 1;
    },
    edge_of(L) {
      const a = checkObj(1, 'node'), b = checkObj(2, 'node');
      const e = scene.edgeOf(a, b);
      if (e === null) lua.lua_pushnil(L); else lua.lua_pushinteger(L, e);
      return 1;
    },
    print(L) {
      const n = lua.lua_gettop(L), parts = [];
      for (let i = 1; i <= n; i++) parts.push(to_jsstring(lauxlib.luaL_tolstring(L, i)));
      log.push(parts.join('\t'));
      return 0;
    },
  };
  for (const [name, fn] of Object.entries(api)) {
    lua.lua_pushjsfunction(L, fn);
    lua.lua_setglobal(L, to_luastring(name));
  }

  let executed = 0;
  lua.lua_sethook(L, (L) => {
    executed += HOOK_EVERY;
    if (executed > MAX_INSTRUCTIONS) fail('script ran too long (infinite loop?)');
  }, lua.LUA_MASKCOUNT, HOOK_EVERY);

  const run = (src, chunk) => {
    let st = lauxlib.luaL_loadbuffer(L, to_luastring(src), null, to_luastring('=' + chunk));
    if (st === lua.LUA_OK) st = lua.lua_pcall(L, 0, 0, 0);
    if (st !== lua.LUA_OK) {
      const msg = lua.lua_tostring(L, -1);
      throw new ScriptError(msg ? to_jsstring(msg) : `${chunk}: error`);
    }
  };

  inStage = true;
  run(stage, 'stage.lua');
  inStage = false;
  const stageCommands = timeline.commands.length;
  run(steps, 'steps.lua');
  run(script, 'script.lua');
  return { scene, timeline, log, stageCommands };
}
