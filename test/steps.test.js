import { test } from 'node:test';
import assert from 'node:assert/strict';
import fengari from 'fengari';
import { runProgram } from '../core/lua_api.js';
import { toStageLua } from '../core/stage_file.js';
import { stepsToLua, buildSteps, pruneSteps, toEditorIds, stepNames, nextStepId } from '../core/steps.js';
import { sceneAt } from '../core/player.js';
import { Scene } from '../core/scene.js';

function stage() {
  const s = new Scene();
  const A = s.addNode('A', 0, 0), B = s.addNode('B', 100, 0);
  const AB = s.addEdge(A, B);
  return { s, A, B, AB };
}

test('steps become plain API calls; "with previous" shares one wait', () => {
  const { s, A, B, AB } = stage();
  const steps = [
    { op: 'color', target: A, color: 'red', dur: 500 },
    { op: 'color', target: AB, color: 'red', dur: 300, together: true },
    { op: 'move', target: B, x: 50, y: 60, dur: 1000 },
    { op: 'wait', dur: 200 },
    { op: 'color', target: A, color: 'black', dur: 500 },
  ];
  const lua = stepsToLua(steps, s);
  assert.equal(lua.split('\n').slice(1).join('\n'), [
    'color(A, "red", 0.5)',
    'color(edge_of(A, B), "red", 0.3); wait(0.5)',
    'move(B, 50, 60, 1); wait(1)',
    'wait(0.2)',
    'color(A, "black", 0.5); wait(0.5)',
    '',
  ].join('\n'));

  const { timeline } = runProgram(fengari, { stage: toStageLua(s), steps: lua });
  const sets = timeline.commands.filter((c) => c.op === 'set').map((c) => c.t);
  assert.deepEqual(sets, [0, 0, 500, 1700]);
  assert.equal(timeline.durationMs, 2200);
});

test('deleting a node drops its steps and its edges\' steps', () => {
  const { s, A, B, AB } = stage();
  const steps = [{ op: 'color', target: AB, color: 'red', dur: 500 }, { op: 'wait', dur: 100 },
    { op: 'color', target: A, color: 'red', dur: 500 }, { op: 'move', target: B, x: 1, y: 1, dur: 500 }];
  s.remove(B);
  assert.deepEqual(pruneSteps(steps, s).map((x) => x.op), ['wait', 'color']);
});

test('behaviour view uses editor ids even after a deletion', () => {
  const s = new Scene();
  const gone = s.addNode('X', 0, 0);
  const A = s.addNode('A', 10, 10), B = s.addNode('B', 20, 20);
  const AB = s.addEdge(A, B);
  s.remove(gone); // editor ids now start at 2; the Lua run numbers from 1
  const steps = [{ op: 'move', target: B, x: 99, y: 99, dur: 500 }];
  const result = runProgram(fengari, { stage: toStageLua(s), steps: stepsToLua(steps, s) });
  const view = toEditorIds(sceneAt(result.timeline, result.timeline.durationMs), result, s);
  assert.deepEqual(view.nodes.map((n) => [n.id, n.x]), [[A, 10], [B, 99]]);
  assert.deepEqual(view.edges.map((e) => [e.id, e.a, e.b]), [[AB, A, B]]);
});

test('steps can add, connect, remove and tidy; objects they create can be used by later steps', () => {
  const s = new Scene();
  const A = s.addNode('A', 100, 100), B = s.addNode('B', 300, 100);
  const AB = s.addEdge(A, B);
  const steps = [
    { op: 'add', id: 's1', shape: 'rect', label: 'A', x: 200, y: 250 },          // label taken: obj_1
    { op: 'connect', id: 's2', a: A, b: 's1', directed: true, together: true },
    { op: 'color', target: 's2', color: 'red', dur: 500 },
    { op: 'remove', target: AB },
    { op: 'tidy', target: A, dur: 400 },
    { op: 'remove', target: 's1' },
  ];
  const { code, stepAtLine } = buildSteps(steps, s);
  assert.equal(code, [
    '-- steps.lua (generated by the GEPV1 steps editor)',
    'obj_1 = rect("A", 200, 250)',
    'arrow(A, obj_1)',
    'color(edge_of(A, obj_1), "red", 0.5); wait(0.5)',
    'remove(edge_of(A, B))',
    'tree_layout(A, 0.4); wait(0.4)',
    'remove(obj_1)',
    '',
  ].join('\n'));
  const r = runProgram(fengari, { stage: toStageLua(s), steps: code });
  const end = sceneAt(r.timeline, r.timeline.durationMs);
  assert.deepEqual(end.nodes.map((n) => n.label), ['A', 'B']);
  assert.equal(end.edges.length, 0);
  // the picture halfway (after the colour step) maps step-created objects back to their step ids
  const mid = toEditorIds(sceneAt(r.timeline, 499), r, s, steps, stepAtLine);
  assert.deepEqual(mid.nodes.map((n) => n.id), [A, B, 's1']);
  assert.deepEqual(mid.edges.map((e) => [e.id, e.a, e.b, e.directed]), [[AB, A, B, false], ['s2', A, 's1', true]]);
  assert.equal(stepNames(steps, s).nameOf('s2'), 'A-A');
  assert.equal(nextStepId(steps), 's3');
});

test('a step is kept only while its object exists at that point; deleting an "add" cascades', () => {
  const s = new Scene();
  const A = s.addNode('A', 100, 100), B = s.addNode('B', 300, 100);
  const AB = s.addEdge(A, B);
  const steps = [
    { op: 'add', id: 's1', shape: 'circle', label: 'C', x: 0, y: 0 },
    { op: 'connect', id: 's2', a: 's1', b: B },
    { op: 'connect', id: 's3', a: A, b: B },        // A and B are already connected: dropped
    { op: 'remove', target: A },                     // takes A-B with it
    { op: 'color', target: AB, color: 'red', dur: 1 }, // A-B is gone by now: dropped
    { op: 'move', target: 's1', x: 5, y: 5, dur: 1 },
    { op: 'color', target: 's2', color: 'red', dur: 1 },
  ];
  assert.deepEqual(pruneSteps(steps, s).map((x) => x.id ?? x.op), ['s1', 's2', 'remove', 'move', 'color']);
  const withoutAdd = pruneSteps(steps.slice(1), s); // the object s1 is gone: everything using it goes
  assert.deepEqual(withoutAdd.map((x) => x.id ?? x.op), ['remove']);
});
